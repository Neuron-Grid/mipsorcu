-- Section 1200: migrate plaintext aliases to encrypted alias storage

do $$
begin
    if exists (select 1 from public.secret_aliases) then
        raise exception 'secret_aliases_migration_requires_empty_table'
            using errcode = '55000';
    end if;
end;
$$;

drop policy if exists secret_aliases_select_own on public.secret_aliases;
drop function if exists public.rpc_create_secret_alias(uuid, uuid, text, text);

alter table public.secret_aliases
    drop constraint if exists secret_aliases_owner_alias_unique,
    drop column alias,
    drop column alias_normalized,
    alter column created_at drop default,
    alter column id drop default,
    add column alias_ciphertext bytea not null,
    add column alias_nonce bytea not null,
    add column alias_key_version integer not null,
    add column alias_fingerprint bytea not null,
    add column alias_fingerprint_key_version integer not null,
    add column alias_fingerprint_schema_version integer not null,
    add column aad_context jsonb not null,
    add column updated_at timestamptz not null default now(),
    add constraint secret_aliases_alias_ciphertext_not_empty
        check (octet_length(alias_ciphertext) > 0),
    add constraint secret_aliases_alias_nonce_length
        check (octet_length(alias_nonce) = 24),
    add constraint secret_aliases_alias_key_version_positive
        check (alias_key_version > 0),
    add constraint secret_aliases_alias_fingerprint_length
        check (octet_length(alias_fingerprint) = 32),
    add constraint secret_aliases_alias_fingerprint_key_version_positive
        check (alias_fingerprint_key_version > 0),
    add constraint secret_aliases_alias_fingerprint_schema_version_supported
        check (alias_fingerprint_schema_version = 1),
    add constraint secret_aliases_aad_context_object
        check (jsonb_typeof(aad_context) = 'object'),
    add constraint secret_aliases_aad_context_required_keys
        check (
            aad_context ?& array[
                'aad_version',
                'alias_key_version',
                'owner_user_id',
                'secret_alias_id',
                'secret_id'
            ]
        ),
    add constraint secret_aliases_aad_context_allowed_keys
        check (
            aad_context - array[
                'aad_version',
                'alias_key_version',
                'owner_user_id',
                'secret_alias_id',
                'secret_id'
            ] = '{}'::jsonb
        ),
    add constraint secret_aliases_aad_context_matches_row
        check (
            jsonb_typeof(aad_context -> 'aad_version') = 'number'
            and jsonb_typeof(aad_context -> 'alias_key_version') = 'number'
            and jsonb_typeof(aad_context -> 'owner_user_id') = 'string'
            and jsonb_typeof(aad_context -> 'secret_alias_id') = 'string'
            and jsonb_typeof(aad_context -> 'secret_id') = 'string'
            and aad_context ->> 'aad_version' = '1'
            and aad_context ->> 'secret_alias_id' = id::text
            and aad_context ->> 'secret_id' = secret_id::text
            and aad_context ->> 'owner_user_id' = owner_user_id::text
            and case
                when aad_context ->> 'alias_key_version' ~ '^[1-9][0-9]*$'
                then (aad_context ->> 'alias_key_version')::integer = alias_key_version
                else false
            end
        ),
    add constraint secret_aliases_owner_alias_fingerprint_unique
        unique (owner_user_id, alias_fingerprint),
    add constraint secret_aliases_owner_secret_unique
        unique (owner_user_id, secret_id);

