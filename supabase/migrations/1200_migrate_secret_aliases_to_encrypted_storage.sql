    return query
    select sa.id,
        sa.secret_id,
        sa.alias_ciphertext,
        sa.alias_nonce,
        sa.alias_key_version,
        sa.aad_context
    from public.secret_aliases sa
    where sa.owner_user_id = p_owner_user_id
        and sa.alias_fingerprint = p_alias_fingerprint;
end;
$$;

